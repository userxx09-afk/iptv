/// The logo as a circle, [size] points across. Draws nothing if the image
/// can't be decoded, so a bad copy never leaves a blank gap.
struct AppLogoView: View {
    var size: CGFloat = 28

    var body: some View {
        if let image = AppLogo.image {
            Image(uiImage: image)
                .resizable()
                .scaledToFill()
                .frame(width: size, height: size)
                .clipShape(Circle())
                .accessibilityHidden(true)
        }
    }
}
